export function getPropertyById(id: string): Property | undefined {
  return MOCK_PROPERTIES.find((p) => p.id === id);
}

export function getFeaturedProperties(): Property[] {
  return MOCK_PROPERTIES.filter((p) => p.isFeatured);
}

export function searchProperties(query: string): Property[] {
  const searchTerm = query.toLowerCase();
  return MOCK_PROPERTIES.filter(
    (p) =>
      p.title.toLowerCase().includes(searchTerm) ||
      p.address.city.toLowerCase().includes(searchTerm) ||
      p.address.locality.toLowerCase().includes(searchTerm) ||
      p.type.toLowerCase().includes(searchTerm)
  );
}
